export function pickRandomTrivia(lang: 'ru' | 'en'): TriviaRound {
  const q = TRIVIA_BANK[Math.floor(Math.random() * TRIVIA_BANK.length)];
  const correct = lang === 'ru' ? q.answersRu[0] : q.answersEn[0];
  const wrongs = (lang === 'ru' ? q.answersRu : q.answersEn).slice(1) as [string, string, string];
  const { options, correctIndex } = shuffleOptions(correct, wrongs);
  return { id: q.id, question: lang === 'ru' ? q.ru : q.en, options, correctIndex };
}
